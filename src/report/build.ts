import { CONDITION_LABELS } from "../conditions/index.js";
import type { ConditionId } from "../conditions/types.js";
import { aggregate, findResultFiles, loadRecords, type ReportData } from "./aggregate.js";

export const RESULTS_START = "<!-- RESULTS:START -->";
export const RESULTS_END = "<!-- RESULTS:END -->";

export interface ReportOptions {
  resultsDir: string;
  outDir: string;
  readme?: string | null;
  includeMock?: boolean;
  taskSetHash?: string;
}

const pct = (x: number) => `${(x * 100).toFixed(1)}%`;
const num = (x: number) => (x >= 10_000 ? `${(x / 1000).toFixed(1)}k` : x >= 100 ? x.toFixed(0) : x.toFixed(1));
const pval = (p: number) => (p < 0.001 ? "<0.001" : p.toFixed(3));
const short = (c: ConditionId) => CONDITION_LABELS[c];

export function renderMarkdown(d: ReportData): string {
  if (d.overall.length === 0) {
    return [
      "_No benchmark results have been published yet._",
      "",
      "Results are generated exclusively from run logs in `results/` by `npm run report`. See [Reproducing the results](#reproducing-the-results) to produce them on your own hardware.",
    ].join("\n");
  }
  const lines: string[] = [];
  lines.push(
    `> Generated by \`npm run report\` from ${d.generatedFrom.includedRows} runs` +
      (d.dateRange ? ` executed ${d.dateRange[0] === d.dateRange[1] ? `on ${d.dateRange[0]}` : `between ${d.dateRange[0]} and ${d.dateRange[1]}`}` : "") +
      `. Task-set fingerprint \`${d.taskSetHash}\`${d.gitCommits.length ? `, harness commit ${d.gitCommits.map((c) => `\`${c}\``).join(", ")}` : ""}. Do not edit this section by hand.`,
  );
  lines.push("");
  lines.push("**Models:** " + d.models.map((m) => `\`${m.model}\` (${[m.provider, m.parameterSize, m.quantization, m.digest ? `digest ${m.digest.slice(0, 12)}` : undefined, m.contextWindow ? `ctx ${m.contextWindow}` : undefined, m.temperature !== undefined ? `T=${m.temperature}` : undefined].filter(Boolean).join(", ")})`).join("; "));
  if (d.hardware.length) lines.push("", "**Hardware:** " + d.hardware.join("; "));
  lines.push("", "| Model | Condition | Tools | Success (95% CI) | n | Mean input tokens | Mean turns | Median time (s) | PII exposed |", "|---|---|---|---|---|---|---|---|---|");
  for (const c of d.byToolCount) {
    lines.push(`| ${c.modelId} | ${short(c.condition)} | ${c.toolCount} | **${pct(c.successRate)}** (${pct(c.ci95[0])}–${pct(c.ci95[1])}) | ${c.n} | ${num(c.meanPromptTokens)} | ${c.meanTurns.toFixed(1)} | ${c.medianWallSeconds.toFixed(1)} | ${c.meanPiiExposed.toFixed(1)} |`);
  }
  if (d.paired.length) {
    lines.push("", "**Paired comparison against direct tool calling** (matched on task × seed; exact McNemar test on discordant pairs):", "");
    lines.push("| Model | Tools | Condition | Pairs | Direct | Condition | Δ | p |", "|---|---|---|---|---|---|---|---|");
    for (const p of d.paired) {
      lines.push(`| ${p.modelId} | ${p.toolCount} | ${short(p.treatment)} | ${p.pairs} | ${pct(p.baselineRate)} | ${pct(p.treatmentRate)} | ${p.delta >= 0 ? "+" : ""}${(p.delta * 100).toFixed(1)} pp | ${pval(p.pValue)} |`);
    }
  }
  const excluded = Object.entries(d.generatedFrom.excluded);
  if (excluded.length) lines.push("", `_Excluded from statistics: ${excluded.map(([k, v]) => `${v} × ${k}`).join("; ")}._`);
  lines.push("", "Input tokens are as reported by the provider. Full breakdowns (by tool count, task category, chain length and failure mode) are in [`reports/index.html`](reports/index.html); raw per-run records and gzipped traces are in [`results/`](results/).");
  return lines.join("\n");
}

