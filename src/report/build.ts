export async function updateReadme(path: string, block: string): Promise<boolean> {
  if (!existsSync(path)) return false;
  const readme = await readFile(path, "utf8");
  const start = readme.indexOf(RESULTS_START);
  const end = readme.indexOf(RESULTS_END);
  if (start === -1 || end === -1 || end < start) return false;
  const next = readme.slice(0, start + RESULTS_START.length) + "\n" + block + "\n" + readme.slice(end);
  if (next !== readme) await writeFile(path, next);
  return true;
}

export async function buildReport(opts: ReportOptions): Promise<ReportData> {
  const files = await findResultFiles(opts.resultsDir);
  const records = await loadRecords(files);
  const data = aggregate(records, files.map((f) => f.replace(/\\/g, "/")), { includeMock: opts.includeMock, taskSetHash: opts.taskSetHash });
  await mkdir(opts.outDir, { recursive: true });
  await writeFile(join(opts.outDir, "summary.json"), JSON.stringify(data, null, 2) + "\n");
  await writeFile(join(opts.outDir, "index.html"), renderHtml(data));
  const md = renderMarkdown(data);
  await writeFile(join(opts.outDir, "results.md"), md + "\n");
  if (opts.readme) {
    await mkdir(dirname(opts.readme), { recursive: true });
    await updateReadme(opts.readme, md);
  }
  return data;
}
